export const arToEn: Record<string, string> = Object.fromEntries(Object.entries(enToAr).map(([english, arabic]) => [arabic, english]));

export function translateText(value: string, language: "en" | "ar") {
  const source = language === "ar" ? enToAr : arToEn;
  const trimmed = value.trim();
  const exact = source[trimmed];
  if (exact) return value.replace(trimmed, exact);

  // Fall back to matching known fragments at the start and/or end of the text,
  // so strings with an interpolated value in the middle (e.g. "Only ${n} left…")
  // or at one end (e.g. "${name} is on the counter.") still translate their
  // static portions instead of leaving one side in the original language.
  const keys = Object.keys(source).sort((a, b) => b.length - a.length);
  const suffixKey = keys.find((key) => trimmed.length > key.length && trimmed.endsWith(key));
  const prefixKey = keys.find((key) => trimmed.length > key.length && trimmed.startsWith(key) && key !== suffixKey);

  if (prefixKey && suffixKey && prefixKey.length + suffixKey.length <= trimmed.length) {
    return value.replace(prefixKey, source[prefixKey]).replace(suffixKey, source[suffixKey]);
  }
  if (suffixKey) return value.replace(suffixKey, source[suffixKey]);
  if (prefixKey) return value.replace(prefixKey, source[prefixKey]);
  return value;
}
